k = 440 / g[(0, 0)]['img'].height
for c in range(5): big.append((f'magnarG_{c}', *fit(g[(0, c)], k, flip=True)))
g = grid_of('astrale.png', 2, 3, thr=128, merge_dist=70)
k = 430 / g[(0, 2)]['img'].height
for (r, c), f in g.items(): big.append((f'astrale_{r * 3 + c}', *fit(f, k)))
save('ferreaG', big)

# ---- the Cuori di Stella armours (front view, for menus and cinematics)
